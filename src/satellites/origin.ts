export const describeOwner = (code: string): string => (code === '' ? 'Desconocido' : (OWNER_NAMES[code] ?? code))

const STATUS_NAMES: Record<string, string> = {
  '+': 'Operativo',
  P: 'Parcialmente operativo',
  B: 'En reserva',
  S: 'En espera de activación',
  X: 'En misión extendida',
  '-': 'No operativo',
}

/** El estado operativo, o `null` si no tiene (los restos); un código raro se dice como desconocido. */
export const describeStatus = (code: string): string | null => (code === '' ? null : (STATUS_NAMES[code] ?? 'Estado desconocido'))

const TYPE_NAMES: Record<ObjectType, string> = {
  PAY: 'Carga útil',
  'R/B': 'Cuerpo de cohete',
  DEB: 'Resto',
  UNK: 'Desconocido',
}
export const describeType = (type: string): string => TYPE_NAMES[type as ObjectType] ?? TYPE_NAMES.UNK
